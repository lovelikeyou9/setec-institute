-- FIRST_NAME || ' ' || LAST_NAME
SELECT FIRST_NAME, LAST_NAME, FIRST_NAME || ' ' || LAST_NAME AS "FullName"
FROM EMPLOYEES;

-- FIRST_NAME || ' ' || LAST_NAME => Clone table EMP_SV26 with data
CREATE TABLE EMP_SV26 AS
SELECT FIRST_NAME || ' ' || LAST_NAME AS "FullName" FROM EMPLOYEES;
SELECT * FROM EMP_SV26;

SELECT "FullName", "FirstName", "LastName" FROM EMP_SV26;

SELECT 
    FIRST_NAME AS FirstName,
    LAST_NAME AS LastName,
    FIRST_NAME || ' ' || LAST_NAME AS FullName
FROM EMPLOYEES;

