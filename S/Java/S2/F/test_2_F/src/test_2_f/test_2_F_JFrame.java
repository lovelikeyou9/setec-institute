    // Receive Enter Number from click then Add or Remove
    private void EnterNumbers(String receiveNumber){
        if (jtxtCalculate.getText().equals("0")){
            jtxtCalculate.setText(receiveNumber); // it will remove 0 and add other number into
        } else {
            jtxtCalculate.setText(jtxtCalculate.getText() + receiveNumber); // it will add but not remove
        }
    }
    
    
    
    
    private void btCActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btCActionPerformed
        // TODO add your handling code here:
        String backSpace = null;
        
        if (jtxtCalculate.getText().length() > 0){
            // StringBuilder can add, remove, modify character
            // ➕ add characters (append)
            // ❌ remove characters (delete, deleteCharAt)
            // ✏️ modify characters (setCharAt, replace)
            StringBuilder sb = new StringBuilder(jtxtCalculate.getText());
            sb.deleteCharAt(jtxtCalculate.getText().length() - 1);
            backSpace = sb.toString();
            jtxtCalculate.setText(backSpace);
            if (jtxtCalculate.getText().length() == 0) {
                jtxtCalculate.setText("0");
            }
        }
        
        
        
        
    }//GEN-LAST:event_btCActionPerformed

    private void btEquActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEquActionPerformed
        // TODO add your handling code here:
        NumEnter2 = Double.parseDouble(jtxtCalculate.getText());
        if ( operator == "+" ){
            Result = NumEnter1 + NumEnter2;
            jtxtCalculate.setText(String.valueOf(Result));
            
        } else if ( operator == "-" ){
            Result = NumEnter1 - NumEnter2;
            jtxtCalculate.setText(String.valueOf(Result));
            
        } else if ( operator == "*" ){
            Result = NumEnter1 * NumEnter2;
            jtxtCalculate.setText(String.valueOf(Result));
        } else if ( operator == "/" ){
            Result = NumEnter1 / NumEnter2;
            jtxtCalculate.setText(String.valueOf(Result));
        }
        
        
        
    }//GEN-LAST:event_btEquActionPerformed

