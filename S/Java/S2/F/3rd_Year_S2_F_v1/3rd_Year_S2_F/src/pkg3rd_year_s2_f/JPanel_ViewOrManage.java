    private void jtbViewReportMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtbViewReportMouseClicked
        // TODO add your handling code here:
        
        try {

            int row = jtbViewReport.getSelectedRow();

            if (row < 0) return;

            // Example columns (adjust if your table is different)
            String col1 = jtbViewReport.getValueAt(row, 0).toString();
            String col2 = jtbViewReport.getValueAt(row, 1).toString();
            String col3 = jtbViewReport.getValueAt(row, 2).toString();

            // Simple preview popup
            javax.swing.JOptionPane.showMessageDialog(this,
                "Report Details:\n"
                + "Data 1: " + col1 + "\n"
                + "Data 2: " + col2 + "\n"
                + "Data 3: " + col3
            );

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
    }//GEN-LAST:event_jtbViewReportMouseClicked


