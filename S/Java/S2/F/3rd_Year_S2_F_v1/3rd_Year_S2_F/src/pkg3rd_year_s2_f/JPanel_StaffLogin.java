    private void jbtStaffShowPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtStaffShowPasswordActionPerformed
        // TODO add your handling code here:
        if(jtxtStaffPassword.getEchoChar() == '*'){
            jtxtStaffPassword.setEchoChar((char)0);
            jbtStaffShowPassword.setText("Hide");
        }else{
            jtxtStaffPassword.setEchoChar('*');
            jbtStaffShowPassword.setText("Show");
        }
        
    }//GEN-LAST:event_jbtStaffShowPasswordActionPerformed

