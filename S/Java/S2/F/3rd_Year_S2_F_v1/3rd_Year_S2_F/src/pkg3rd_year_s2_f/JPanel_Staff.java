    private void jtbBuildAndRoomMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtbBuildAndRoomMouseClicked
        // TODO add your handling code here:

        int viewRow = jtbBuildAndRoom.getSelectedRow();

        if (viewRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a room first");
            return;
        }

        try {

            // 🔥 FIX FOR SORTING
            int row = jtbBuildAndRoom.convertRowIndexToModel(viewRow);

            String roomId = jtbBuildAndRoom.getValueAt(row, 0).toString();
            String building = jtbBuildAndRoom.getValueAt(row, 1).toString();
            String roomNumber = jtbBuildAndRoom.getValueAt(row, 2).toString();
            String status = jtbBuildAndRoom.getValueAt(row, 3).toString();

            // fill UI
            jtxtCustomerBuilding.setText(building);
            jtxtCustomerRoom.setText(roomNumber);

            // show info
            JOptionPane.showMessageDialog(this,
                    "Room ID: " + roomId
                    + "\nBuilding: " + building
                    + "\nRoom: " + roomNumber
                    + "\nStatus: " + status
            );

            // warning
            if ("Occupied".equalsIgnoreCase(status)) {
                JOptionPane.showMessageDialog(this,
                        "⚠ This room is already OCCUPIED");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error loading room data: " + e.getMessage());
        }


    }//GEN-LAST:event_jtbBuildAndRoomMouseClicked

