    private void jbtCheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtCheckoutActionPerformed
        // TODO add your handling code here:

 try {

        String room = jtxtCustomerRoom.getText().trim();
        String checkedBy = loggedStaff;

        Connection con = DBConnection.getConnection();

        // get room price + status
        PreparedStatement pstRoom = con.prepareStatement(
            "SELECT room_price FROM tbl_room WHERE room_number=?"
        );
        pstRoom.setString(1, room);
        ResultSet rsRoom = pstRoom.executeQuery();

        if (!rsRoom.next()) {
            JOptionPane.showMessageDialog(this, "Room not found");
            return;
        }

        double roomPrice = rsRoom.getDouble("room_price");

        // active booking
        PreparedStatement pst = con.prepareStatement(
            "SELECT booking_id, checkout_date, customer_type FROM tbl_booking WHERE room_number=? AND status='Checked-In' ORDER BY booking_id DESC LIMIT 1"
        );
        pst.setString(1, room);
        ResultSet rs = pst.executeQuery();

        if (!rs.next()) {
            JOptionPane.showMessageDialog(this, "No active check-in");
            return;
        }

        int bookingId = rs.getInt("booking_id");
        Timestamp planCheckout = rs.getTimestamp("checkout_date");
        String type = rs.getString("customer_type");

        Timestamp now = new Timestamp(System.currentTimeMillis());

        // penalty
        double penalty = 0;

        if (planCheckout != null && now.after(planCheckout)) {

            long hours = (now.getTime() - planCheckout.getTime()) / (1000 * 60 * 60);
            if (hours < 1) hours = 1;

            double hourly = roomPrice / 24;
            penalty = hours * hourly * 1.5;
        }

        // 💰 PAYMENT RULE
        double basePayment;

        if (type != null && type.equalsIgnoreCase("Walk-in")) {
            basePayment = roomPrice; // 100%
        } else {
            basePayment = roomPrice * 0.80; // booked
        }

        double total = basePayment + penalty;

        // update booking
        PreparedStatement up = con.prepareStatement(
            "UPDATE tbl_booking SET status='Checked-Out', checked_out_by=? WHERE booking_id=?"
        );
        up.setString(1, checkedBy);
        up.setInt(2, bookingId);
        up.executeUpdate();

        // update room
        PreparedStatement roomUp = con.prepareStatement(
            "UPDATE tbl_room SET status='Available' WHERE room_number=?"
        );
        roomUp.setString(1, room);
        roomUp.executeUpdate();

        // income save
        PreparedStatement income = con.prepareStatement(
            "INSERT INTO tbl_income(date, booking_income, room_income, total_income) VALUES (NOW(),?,?,?)"
        );
        income.setDouble(1, basePayment);
        income.setDouble(2, 0);
        income.setDouble(3, total);
        income.executeUpdate();

        JOptionPane.showMessageDialog(this,
            "CHECK-OUT SUCCESS\nTotal: " + total +
            "\nPenalty: " + penalty);

        loadRooms();
        clearFields();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_jbtCheckoutActionPerformed

