    private void jbtAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtAddActionPerformed
        // TODO add your handling code here:
        
        try {

            Connection con = DBConnection.getConnection();

            PreparedStatement pst = con.prepareStatement(
                "INSERT INTO tbl_room(building_name,room_number,room_type,room_price,status) VALUES(?,?,?,?,?)"
            );

            pst.setString(1, jtxtBuildingName.getText());
            pst.setString(2, jtxtRoomNumber.getText());
            pst.setString(3, jcbbRoomType.getSelectedItem().toString());
            pst.setDouble(4, Double.parseDouble(jtxtBuildingOrRoomPrice.getText()));
            pst.setString(5, jcbbStatus.getSelectedItem().toString());

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Room Added");

            loadRoom();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
    }//GEN-LAST:event_jbtAddActionPerformed

    private void jbtUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtUpdateActionPerformed
        // TODO add your handling code here:
        
        try {

            int row = jtbManageBuildingOrRoom.getSelectedRow();

            if (row < 0) {
                JOptionPane.showMessageDialog(this, "Select Row First");
                return;
            }

            int id = Integer.parseInt(
                jtbManageBuildingOrRoom.getValueAt(row, 0).toString()
            );

            Connection con = DBConnection.getConnection();

            PreparedStatement pst = con.prepareStatement(
                "UPDATE tbl_room SET building_name=?,room_number=?,room_type=?,room_price=?,status=? WHERE room_id=?"
            );

            pst.setString(1, jtxtBuildingName.getText());
            pst.setString(2, jtxtRoomNumber.getText());
            pst.setString(3, jcbbRoomType.getSelectedItem().toString());
            pst.setDouble(4, Double.parseDouble(jtxtBuildingOrRoomPrice.getText()));
            pst.setString(5, jcbbStatus.getSelectedItem().toString());
            pst.setInt(6, id);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Room Updated");

            loadRoom();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
        
    }//GEN-LAST:event_jbtUpdateActionPerformed

    private void jbtDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtDeleteActionPerformed
        // TODO add your handling code here:
        try {

            int row = jtbManageBuildingOrRoom.getSelectedRow();

            if (row < 0) {
                JOptionPane.showMessageDialog(this, "Select Row First");
                return;
            }

            int id = Integer.parseInt(
                jtbManageBuildingOrRoom.getValueAt(row, 0).toString()
            );

            Connection con = DBConnection.getConnection();

            PreparedStatement pst = con.prepareStatement(
                "DELETE FROM tbl_room WHERE room_id=?"
            );

            pst.setInt(1, id);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Room Deleted");

            loadRoom();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_jbtDeleteActionPerformed

