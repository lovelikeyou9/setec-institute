    public void loadHistory() {

        try {

            Connection con = DBConnection.getConnection();

            PreparedStatement pst = con.prepareStatement(
                "SELECT * FROM tbl_booking ORDER BY booking_id DESC"
            );

            ResultSet rs = pst.executeQuery();

            DefaultTableModel model =
                (DefaultTableModel) jtbViewHistoryOrReport.getModel();

            model.setRowCount(0);

            int count = 0;

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("booking_id"),
                    rs.getString("guest_name"),
                    rs.getString("room_number"),
                    rs.getString("checkin_date"),
                    rs.getString("checkout_date"),
                    rs.getDouble("deposit"),
                    rs.getString("status")
                });

                count++;
            }

            jtxtTotalRecord.setText(String.valueOf(count));

            // always refresh finance after loading
            calculateFinance();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    } 
    
private void searchHistory() {

    try {

        String keyword = jtxtSearch.getText().trim();

        Connection con = DBConnection.getConnection();

        PreparedStatement pst = con.prepareStatement(
            "SELECT * FROM tbl_booking WHERE guest_name LIKE ? ORDER BY booking_id DESC"
        );

        pst.setString(1, "%" + keyword + "%");

        ResultSet rs = pst.executeQuery();

        DefaultTableModel model =
            (DefaultTableModel) jtbViewHistoryOrReport.getModel();

        model.setRowCount(0);

        int count = 0;

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("booking_id"),
                rs.getString("guest_name"),
                rs.getString("room_number"),
                rs.getString("checkin_date"),
                rs.getString("checkout_date"),
                rs.getDouble("deposit"),
                rs.getString("status")
            });

            count++;
        }

        jtxtTotalRecord.setText(String.valueOf(count));

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}
    
private void calculateFinance() {

    try {

        Connection con = DBConnection.getConnection();

        PreparedStatement pst = con.prepareStatement(
            "SELECT SUM(deposit) FROM tbl_booking"
        );

        ResultSet rs = pst.executeQuery();

        double income = 0;

        if (rs.next()) {
            income = rs.getDouble(1);
        }

        if (Double.isNaN(income)) income = 0;

        double expense = income * 0.2;
        double net = income - expense;

        jtxtIncome.setText(String.format("%.2f", income));
        jtxtExpense.setText(String.format("%.2f", expense));
        jtxtNet.setText(String.format("%.2f", net));

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}  
    
    
    
    
