    private void jtbViewHistoryOrReportMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtbViewHistoryOrReportMouseClicked
        // TODO add your handling code here:       
        
        try {

            int row = jtbViewHistoryOrReport.getSelectedRow();

            if (row < 0) {
                JOptionPane.showMessageDialog(this, "Please select a record first");
                return;
            }

            String id = jtbViewHistoryOrReport.getValueAt(row, 0).toString();
            String guest = jtbViewHistoryOrReport.getValueAt(row, 1).toString();
            String room = jtbViewHistoryOrReport.getValueAt(row, 2).toString();
            String checkin = jtbViewHistoryOrReport.getValueAt(row, 3).toString();
            String checkout = jtbViewHistoryOrReport.getValueAt(row, 4).toString();
            String deposit = jtbViewHistoryOrReport.getValueAt(row, 5).toString();
            String status = jtbViewHistoryOrReport.getValueAt(row, 6).toString();

            // Fill search field (quick filter)
            jtxtSearch.setText(guest);

            // Optional detailed popup (very useful for admin)
            JOptionPane.showMessageDialog(this,
                "Booking ID: " + id +
                "\nGuest: " + guest +
                "\nRoom: " + room +
                "\nCheck-in: " + checkin +
                "\nCheck-out: " + checkout +
                "\nDeposit: " + deposit +
                "\nStatus: " + status
            );

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }

        
    }//GEN-LAST:event_jtbViewHistoryOrReportMouseClicked

