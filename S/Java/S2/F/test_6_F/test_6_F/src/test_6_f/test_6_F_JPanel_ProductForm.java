    private void jbtUpdateProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtUpdateProductActionPerformed
        // TODO add your handling code here:
        if(selectedID == -1) return;
        
        try {
            pst = con.prepareStatement(
                "UPDATE product SET Name=?, Price=?, SQty=? WHERE ID=?"
            );
            
            pst.setString(1, jtxtName.getText());
            pst.setDouble(2, Double.parseDouble(jtxtPrice.getText()));
            pst.setInt(3, Integer.parseInt(jtxtQty.getText()));
            pst.setInt(4, selectedID);
            
            pst.executeUpdate();
            loadData();
            clear();
            
        } catch (NumberFormatException | SQLException e) {
        }
    }//GEN-LAST:event_jbtUpdateProductActionPerformed

    private void jtbProductMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtbProductMouseClicked
        // TODO add your handling code here:
        int row = jtbProduct.getSelectedRow();
        DefaultTableModel model = (DefaultTableModel) jtbProduct.getModel();
        
        selectedID = (int) model.getValueAt(row, 0);
        jtxtName.setText(model.getValueAt(row, 1).toString());
        jtxtPrice.setText(model.getValueAt(row, 2).toString());
        jtxtQty.setText(model.getValueAt(row, 3).toString());
    }//GEN-LAST:event_jtbProductMouseClicked

