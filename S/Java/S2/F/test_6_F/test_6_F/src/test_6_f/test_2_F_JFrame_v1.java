        if (textCalculate == null || textCalculate.isEmpty() || textCalculate.equals("0")) {
            return; 
        }

        // 1. Identify the last "token" (the number or the parenthesized negative number)
        // We scan backward to find the split point where the last number starts.
        int splitIndex = -1;
        
        // String textCalculate = "1+(-5)";
        // endsWith is true/false
        // if textCalculate at the end have ) is true
