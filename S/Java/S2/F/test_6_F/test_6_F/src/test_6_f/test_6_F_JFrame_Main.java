    private void switchPanel(JPanel panel){
        
        // Clears old content
        jpnRightPanel.removeAll();
        
        // ets layout so panel fills space
        jpnRightPanel.setLayout(new BorderLayout());
        
        // Adds new screen in the center
        jpnRightPanel.add(panel, BorderLayout.CENTER);
        
        
        // used to tell the UI to re-check and rebuild its layout
        jpnRightPanel.revalidate();
        
        // used to redraw the panel on the screen
        jpnRightPanel.repaint();
    }
    
