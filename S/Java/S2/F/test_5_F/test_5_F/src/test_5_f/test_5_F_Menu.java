    private void jmiOpenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmiOpenActionPerformed
        // TODO add your handling code here:
        
        /*
        🔹 this
        👉 means current object (already exists)

        🔹 this
        👉 does NOT create memory
        It only refers to already existing object

        🔹 new
        👉 means create a new object and new usually use with GUI, Constructor, Method

        🔹 new
        👉 creates new memory (new object / slot in memory)
        */
        
        JFileChooser fileChooser = new JFileChooser();
        // [ this ] attach dialog to current JFrame
        int result = fileChooser.showOpenDialog(this);
        
        /*
        It returns APPROVE_OPTION when the user:
        ✔ Selects a file
        ✔ Clicks Open (or Save in save dialog)
        
        APPROVE_OPTION
        👉 The user selected a file and clicked "Open" (or "Save")
        
        💡 Easy memory:
        APPROVE_OPTION = OK / Open clicked
        */
        if(result == JFileChooser.APPROVE_OPTION) { // == 0
            
            // getSelectedFile() used to get the file that the user selected in JFileChooser.
            /*
            🔹 Simple meaning:
            It returns the file the user clicked and chose.
            
            🔥 What it gives you:
            file contains:
            file name
            file path
            file info

            Example: C:\Users\User\Desktop\image.png
            */
            File file = fileChooser.getSelectedFile();
            
            // getName() 👉 It returns ONLY the file name, not the full path.
            /*
            📂 Example
            If user selects:
            C:\Users\PC\Desktop\report.txt

            Then:
            file.getName()

            👉 Result:
            report.txt
            
            🧠 Simple memory trick:
            👉 Name = just name
            👉 Path = full location
            */
            JOptionPane.showMessageDialog(this, "Select: " + file.getName());
        }
        
        // new JFrameOpen().setVisable(true);
        // this.dispose();
        
    }//GEN-LAST:event_jmiOpenActionPerformed

