    private void jbtBrowseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtBrowseActionPerformed
        // TODO add your handling code here:
        
        // # JFileChooser for Select files from computer #
        JFileChooser chooser = new JFileChooser();
        // this tells it which window to attach then true
        if ( chooser.showOpenDialog(this) == JFileChooser.APPROVE_OPTION ) {
            // chooser.showOpenDialog(this)
            File file = chooser.getSelectedFile();
            // getAbsolutePath give path to find file but not give file
            jlblPicture.setText(file.getAbsolutePath());
            // # Image for Show images in UI #
            ImageIcon icon = new ImageIcon(file.getAbsolutePath());
            // # Image for Work with images #
            // Example: resize, scale, or store image data.
            Image img = icon.getImage().getScaledInstance(jlblPicture.getWidth(), jlblPicture.getHeight(), Image.SCALE_SMOOTH);
            imageHold = jlblPicture.getText(); 
            
            // final process to display image on label
            jlblPicture.setIcon(new ImageIcon(img));
            
            // imageHold1.add(jlblPicture.getText());
            
            // jlblPicture.setVisible(false);
            jlblPicture.setText("");
        }
        
    }//GEN-LAST:event_jbtBrowseActionPerformed

    private void jbtAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtAddActionPerformed
        // TODO add your handling code here:
        int id = Integer.parseInt(jtxtfId.getText());
        String name = jtxtfName.getText();
        String sex = jcbbSex.getSelectedItem().toString();
        int age = Integer.parseInt(jtxtfAge.getText());
        
        // Load and Scale image
        // String imagePath = imageHold1.get(imageHold1.size() - 1);
        String imagePath = imageHold;
        ImageIcon icon = new ImageIcon(imagePath);
        // SCALE_SMOOTH used when resizing an image to make it look smooth and high quality.
        // Image scaled = icon.getImage().getScaledInstance(jlblPicture.getWidth(), jlblPicture.getHeight(), Image.SCALE_SMOOTH);
        Image scaled = icon.getImage().getScaledInstance(80, 80, Image.SCALE_SMOOTH);
        ImageIcon scaledIcon = new ImageIcon(scaled);
        
        String status = "Added";
        
        // addRow use to add row table [ follow index by index ]
        // row in table is not array
        // JTable uses an array as input, then extracts the values and stores them internally as row data
        model.addRow(new Object[]{id, name, sex, age, scaledIcon, status});
        
        // Object[] row = {id, name, sex, age, scaledIcon};
        // model.addRow(row);
        
        clearInput();
        
    }//GEN-LAST:event_jbtAddActionPerformed

    private void jbtUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtUpdateActionPerformed
        // TODO add your handling code here:
        int row = jtableInformation.getSelectedRow();
        if (row != -1) {
            // use row inside it because row tells Java which row in the table you want to update
            // setValueAt() used to change/set a value in ONE specific cell in a JTable.
            model.setValueAt(jtxtfId.getText(), row, 0);
            model.setValueAt(jtxtfName.getText(), row, 1);
            model.setValueAt(jcbbSex.getSelectedItem().toString(), row, 2);
            model.setValueAt(jtxtfAge.getText(), row, 3);
            model.setValueAt(jlblPicture.getIcon(), row, 4);
            model.setValueAt("Updated", row, 5);
        }
        
        clearInput();
        
    }//GEN-LAST:event_jbtUpdateActionPerformed

